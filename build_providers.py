"""Build providers.yaml from new-api's channels.csv (plaintext keys).

    python3 build_providers.py channels.csv providers.yaml

Prints counts only, never key material.
"""
import csv
import json
import re
import sys
from collections import defaultdict
from urllib.parse import urlparse

SRC, OUT = sys.argv[1], sys.argv[2]

ALIASES = {
    "generativelanguage.googleapis.com": "gemini",
    "api.groq.com": "groq",
    "api.mistral.ai": "mistral",
    "integrate.api.nvidia.com": "nvidia",
    "openrouter.ai": "openrouter",
    "api.cloudflare.com": "cloudflare",
    "api.z.ai": "zai",
    "api.cerebras.ai": "cerebras",
    "text.pollinations.ai": "pollinations",
    "hades-ubuntu.arpa": "hades-local",
    "localhost": "chatjimmy-local",
}


def base(url):
    """Strip the path suffix new-api appends, leaving the OpenAI-style root."""
    url = url.split("#")[0].rstrip("/")
    url = re.sub(r"/(chat/completions|completions|messages)$", "", url)
    return url


def name_for(url):
    host = urlparse(url).hostname or url
    alias = ALIASES.get(host, host.replace(".", "-"))
    # Cloudflare puts the account id in the path, so several accounts share a host.
    if host == "api.cloudflare.com":
        account = [p for p in urlparse(url).path.split("/") if len(p) == 32]
        if account:
            alias = f"{alias}-{account[0][:8]}"
    return alias


channels = defaultdict(lambda: {"keys": [], "models": set(), "priority": 0, "names": []})

with open(SRC, newline="") as f:
    for row in csv.DictReader(f):
        url = base(row["base_url"])
        c = channels[url]
        c["names"].append(row["name"])
        c["priority"] = max(c["priority"], int(row["priority"] or 0))
        for key in re.split(r"[\n,]+", row["key"]):
            key = key.strip()
            if key and key not in c["keys"]:
                c["keys"].append(key)
        # model_mapping says which real model the channel's "auto" resolves to.
        try:
            c["models"].update(json.loads(row["model_mapping"] or "{}").values())
        except json.JSONDecodeError:
            pass

# freellmapi-keys.csv holds extra keys with no base_url of their own. Merge in
# the ones whose platform already matches a channel above; the rest need a URL
# supplied before they are usable.
EXTRA = "freellmapi-keys.csv"
PLATFORM_TO_NAME = {"google": "gemini"}
merged, orphans = 0, defaultdict(int)
try:
    by_name = {name_for(u): c for u, c in channels.items()}
    for row in csv.DictReader(open(EXTRA, newline="")):
        key, platform = row["key"].strip(), row["platform"].strip()
        target = by_name.get(PLATFORM_TO_NAME.get(platform, platform))
        if target is None:
            orphans[platform] += 1
        elif key and key not in target["keys"]:
            target["keys"].append(key)
            merged += 1
except FileNotFoundError:
    pass

lines = [
    "# Generated by build_providers.py from new-api's channels.csv.",
    "# CONTAINS LIVE API KEYS IN PLAINTEXT. Do not commit this file.",
    "providers:",
]
for url, c in sorted(channels.items(), key=lambda x: -x[1]["priority"]):
    lines.append(f"  - name: {name_for(url)}")
    lines.append("    wire: openai")
    lines.append(f"    base_url: {url}")
    lines.append(f"    priority: {c['priority']}   # from new-api, highest first")
    if c["models"]:
        lines.append(f"    known_models: [{', '.join(sorted(c['models']))}]")
    lines.append("    keys:")
    lines.extend(f"      - {k}" for k in c["keys"])

with open(OUT, "w") as f:
    f.write("\n".join(lines) + "\n")

print(f"channels: {len(channels)}   keys: {sum(len(c['keys']) for c in channels.values())}")
print(f"merged from {EXTRA}: {merged}")
if orphans:
    print(f"unused, no base_url known: {dict(sorted(orphans.items()))}")
for url, c in sorted(channels.items(), key=lambda x: -x[1]["priority"]):
    print(f"  {name_for(url):22} keys={len(c['keys']):>2}  pri={c['priority']:>3}  {url[:54]}")


def _selfcheck():
    assert base("https://api.groq.com/openai/chat/completions#") == "https://api.groq.com/openai"
    assert base("https://openrouter.ai/api/v1/chat/completions#") == "https://openrouter.ai/api/v1"
    assert base("http://localhost:4100") == "http://localhost:4100"
    cf = "https://api.cloudflare.com/client/v4/accounts/" + "b" * 32 + "/ai/v1"
    assert name_for(cf) == "cloudflare-bbbbbbbb", name_for(cf)
    assert name_for("https://api.groq.com/openai") == "groq"


_selfcheck()
